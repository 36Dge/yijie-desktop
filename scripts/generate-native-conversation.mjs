import { spawnSync } from "node:child_process";
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const require=createRequire(path.join(root,"../yijie-contracts/package.json"));
const {compile}=require("json-schema-to-typescript");
const publicSpec=JSON.parse(await fs.readFile(path.join(root,"src-tauri/contracts/native-conversation.json"),"utf8"));
const privateSpec=JSON.parse(await fs.readFile(path.join(root,"src-tauri/schemas/chat-native-conversation-v1.schema.json"),"utf8"));
const schemas={...publicSpec.components.schemas,...privateSpec.definitions};
const snake=name=>name.replace(/([a-z0-9])([A-Z])/g,"$1_$2").toLowerCase();
const pascal=name=>name.replace(/(^|[_-])([a-z])/g,(_,a,b)=>b.toUpperCase());
const definitions=[];
function rustType(schema,name){
 if(schema.$ref)return schema.$ref.split("/").at(-1);
 if(schema.type==="object") {emit(schema,name);return name;}
 if(schema.type==="array")return `Vec<${rustType(schema.items,name+"Item")}>`;
 if(schema.type==="integer")return "i64";
 if(schema.type==="boolean")return "bool";
 return "String";
}
function emit(schema,name){
 if(schema.type!=="object")return;
 const fields=Object.entries(schema.properties).map(([key,value])=>{
  let type=rustType(value,name+pascal(key));const required=(schema.required??[]).includes(key);const optional=!required||value.nullable;
  if(optional)type=`Option<${type}>`;
  return `    #[serde(rename = ${JSON.stringify(key)}${!required?', default, skip_serializing_if = "Option::is_none"':''})]\n    pub ${snake(key)==="type"?"kind":snake(key)}: ${type},`;
 }).join("\n");
 definitions.push(`#[derive(Clone, PartialEq, serde::Serialize, serde::Deserialize)]\n#[serde(deny_unknown_fields)]\npub struct ${name} {\n${fields}\n}\nimpl std::fmt::Debug for ${name} {\n fn fmt(&self,f:&mut std::fmt::Formatter<'_>)->std::fmt::Result { f.write_str("${name}([REDACTED])") }\n}`);
}
for(const [name,schema]of Object.entries(schemas))emit(schema,name);
function jsonSchema(value){
 if(Array.isArray(value))return value.map(jsonSchema);
 if(!value||typeof value!=="object")return value;
 const out={};for(const[k,v]of Object.entries(value)){if(k==="nullable")continue;out[k]=k==="$ref"?v.replace("#/components/schemas/","#/definitions/"):jsonSchema(v);}
 if(value.nullable)return {anyOf:[out,{type:"null"}]};return out;
}
const combined={...jsonSchema(privateSpec),definitions:jsonSchema(schemas)};
const validationSource=JSON.parse(JSON.stringify(combined));
const ts=await compile({...combined.definitions.NativeConversationViewEvent, definitions:combined.definitions},"NativeConversationViewEvent",{bannerComment:"/* Generated from native conversation source contracts. Do not edit. */"});
const historyTs=await compile({...validationSource.definitions.NativeConversationHistory,definitions:validationSource.definitions},"NativeConversationHistory",{bannerComment:"/* Generated from native conversation source contracts. Do not edit. */"});
const Ajv=require("ajv").default;
const standalone=require("ajv/dist/standalone").default;
const ajv=new Ajv({strict:false,code:{source:true,esm:true},formats:{int32:true,int64:true}});
ajv.addSchema({...validationSource.definitions.NativeConversationViewEvent,definitions:validationSource.definitions},"native-view-event");
ajv.addSchema({...validationSource.definitions.NativeConversationHistory,definitions:validationSource.definitions},"native-history");
const validationCode='/* Generated by AJV from source contracts. Do not edit. */\nimport ucs2length from "ajv/dist/runtime/ucs2length.js";\n'+standalone(ajv,{validateNativeViewEvent:"native-view-event",validateNativeHistory:"native-history"}).replaceAll('require("ajv/dist/runtime/ucs2length").default',"ucs2length");
const rustSource=`// Generated by scripts/generate-native-conversation.mjs. Do not edit.\n${definitions.join("\n\n")}\n`;
const formatted=spawnSync("rustfmt",["--edition","2021"],{input:rustSource,encoding:"utf8"});
if(formatted.status!==0)throw new Error(formatted.stderr||"rustfmt failed");
const outputs=[
 ["src/api/generated/native-conversation-history.gen.ts",historyTs],
 ["src/api/generated/native-conversation-validator.gen.js",validationCode],
 ["src/api/generated/native-conversation-validator.gen.d.ts",'import type {NativeConversationViewEvent} from "./native-conversation-private.gen";\nimport type {NativeConversationHistory} from "./native-conversation-history.gen";\nexport declare function validateNativeViewEvent(value: unknown): value is NativeConversationViewEvent;\nexport declare function validateNativeHistory(value: unknown): value is NativeConversationHistory;\n'],
 ["src-tauri/src/chat/native_conversation_generated.rs",formatted.stdout],
 ["src/api/generated/native-conversation-private.gen.ts",ts],
 ["src-tauri/schemas/chat-native-conversation-resolved.schema.json",JSON.stringify(combined,null,2)+"\n"],
];
for(const[file,content]of outputs){const target=path.join(root,file);if(process.argv.includes("--check")){if(await fs.readFile(target,"utf8")!==content)throw new Error(`Native conversation generation drift: ${file}`)}else{await fs.mkdir(path.dirname(target),{recursive:true});await fs.writeFile(target,content);}}
