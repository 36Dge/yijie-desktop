import { afterEach, describe, expect, it } from "vitest";
import { mkdtempSync, mkdirSync, readFileSync, writeFileSync, rmSync, statSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { syncMarketCatalog } from "./market-catalog-source.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const catalogBytes = readFileSync(path.join(root, "../yijie-connectors/catalog/market-catalog.v1.json"));
const temporary = [];
afterEach(() => { for (const directory of temporary.splice(0)) rmSync(directory, {recursive: true}); });
function fixture() {
  const directory = mkdtempSync(path.join(tmpdir(), "yijie-catalog-source-")); temporary.push(directory);
  const desktopRoot = path.join(directory, "desktop"), connectorsRoot = path.join(directory, "connectors");
  mkdirSync(path.join(desktopRoot, "contracts"), {recursive: true});
  mkdirSync(path.join(connectorsRoot, "catalog"), {recursive: true});
  const source = path.join(connectorsRoot, "catalog/market-catalog.v1.json");
  writeFileSync(source, catalogBytes);
  const git = (...args) => execFileSync("git", ["-c", "core.hooksPath=/dev/null", "-c", "commit.gpgsign=false", "-c", "user.name=Catalog Test", "-c", "user.email=catalog@example.invalid", "-C", connectorsRoot, ...args], {encoding:"utf8", stdio:["ignore", "pipe", "pipe"]}).trim();
  git("init", "-b", "main"); git("add", "catalog"); git("commit", "-m", "normal catalog source");
  const first = git("rev-parse", "HEAD");
  const advance = () => { writeFileSync(path.join(connectorsRoot, "README.md"), "Ordinary unrelated documentation.\n"); git("add", "README.md"); git("commit", "-m", "documentation only"); return git("rev-parse", "HEAD"); };
  return {desktopRoot, connectorsRoot, source, first, advance};
}
const receipt = fixture => path.join(fixture.desktopRoot, "contracts/market-catalog.candidate.json");

describe("catalog generation provenance", () => {
  it("keeps both checks and no-op sync reproducible after an unrelated commit", () => {
    const f = fixture(); syncMarketCatalog(f);
    const original = readFileSync(receipt(f)); const modifiedAt = statSync(receipt(f)).mtimeMs;
    expect(f.advance()).not.toBe(f.first);
    expect(syncMarketCatalog({...f, check:true}).baseCommit).toBe(f.first);
    syncMarketCatalog(f);
    expect(readFileSync(receipt(f))).toEqual(original);
    expect(statSync(receipt(f)).mtimeMs).toBe(modifiedAt);
  });
  it("still detects real source drift and records it only through explicit sync", () => {
    const f = fixture(); syncMarketCatalog(f); const baseline = readFileSync(receipt(f));
    const newHead = f.advance();
    writeFileSync(f.source, JSON.stringify(JSON.parse(catalogBytes), null, 4) + "\n");
    expect(() => syncMarketCatalog({...f, check:true})).toThrow(/catalog source\/generated bytes/);
    expect(readFileSync(receipt(f))).toEqual(baseline);
    const result = syncMarketCatalog(f); expect(result.baseCommit).toBe(newHead);
    expect(syncMarketCatalog({...f, check:true})).toEqual(result);
    expect(JSON.parse(readFileSync(receipt(f)))).toMatchObject({mode:"local_worktree_candidate", release:false});
  });
  it("checks the generated copy and recorded metadata independently", () => {
    const f = fixture(); syncMarketCatalog(f);
    const output = path.join(f.desktopRoot, "contracts/market-catalog.json");
    writeFileSync(output, JSON.stringify(JSON.parse(catalogBytes)));
    expect(() => syncMarketCatalog({...f, check:true})).toThrow(/market-catalog.json/);
    writeFileSync(output, catalogBytes);
    const prior = JSON.parse(readFileSync(receipt(f)));
    writeFileSync(receipt(f), JSON.stringify({...prior, source_sha256: "0".repeat(64)}, null, 2) + "\n");
    expect(() => syncMarketCatalog({...f, check:true})).toThrow(/candidate.json/);
  });
  it("preserves qualified HEAD and committed-catalog requirements", () => {
    const f = fixture(); const options = {...f, immutableCommit:f.first};
    syncMarketCatalog(options); expect(syncMarketCatalog({...options, check:true}).baseCommit).toBe(f.first);
    writeFileSync(f.source, JSON.stringify(JSON.parse(catalogBytes)));
    expect(() => syncMarketCatalog({...options, check:true})).toThrow(/qualified Git object/);
    writeFileSync(f.source, catalogBytes); f.advance();
    expect(() => syncMarketCatalog({...options, check:true})).toThrow(/qualified checkout/);
  });
  it("checks real receipts without changing catalog, pins or source hashes", () => {
    const names = ["market-catalog.json", "market-catalog.candidate.json", "market-catalog-feat164.candidate.json"];
    const before = names.map(name => readFileSync(path.join(root, "contracts", name)));
    syncMarketCatalog({desktopRoot:root, connectorsRoot:path.join(root, "../yijie-connectors"), check:true});
    syncMarketCatalog({desktopRoot:root, connectorsRoot:path.join(root, "../yijie-connectors"), check:true, immutableCommit:"07c280e72f2f3ccca630d1576376d1b995c9c494"});
    expect(names.map(name => readFileSync(path.join(root, "contracts", name)))).toEqual(before);
  });
});
