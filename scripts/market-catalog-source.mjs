import assert from "node:assert/strict";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { validateCatalogEntry } from "../src/api/generated/market-connectors-validator.gen.js";

const source = "catalog/market-catalog.v1.json";
const output = "contracts/market-catalog.json";
const digest = bytes => createHash("sha256").update(bytes).digest("hex");
const git = (root, ...args) => execFileSync("git", ["-C", root, ...args], { maxBuffer: 1024 * 1024 });

function verifyBase(root, commit) {
  assert.match(commit ?? "", /^[a-f0-9]{40}$/, "Catalog baseline requires a full Git commit");
  assert.equal(git(root, "rev-parse", "--verify", `${commit}^{commit}`).toString().trim(), commit,
    "Catalog baseline must resolve to the recorded commit");
  // A local-worktree baseline is not an immutable source claim. Its worktree
  // bytes are independently bound by the source hash and generated comparison.
  return git(root, "show", `${commit}:${source}`);
}

/** Reuse the existing source/schema and both receipt profiles. No catalog or
 * provider semantics change; checks never update the recorded baseline. */
export function syncMarketCatalog({ desktopRoot, connectorsRoot, check = false, immutableCommit }) {
  const bytes = readFileSync(path.join(connectorsRoot, source));
  const catalog = JSON.parse(bytes);
  assert.equal(catalog.catalogRevision, 11);
  assert.equal(catalog.catalog.length, 61);
  assert.equal(new Set(catalog.catalog.map(item => item.serviceId)).size, 61);
  for (const entry of catalog.catalog) {
    assert.ok(validateCatalogEntry(entry), "Invalid catalog entry");
    assert.equal(entry.serviceId, entry.serverName);
    assert.equal(entry.serviceId, entry.iconAssetId);
    assert.equal(entry.availability === "available", false, "Unqualified service cannot be activated");
    assert.ok(entry.blockerCodes.length > 0);
  }
  const receipt = immutableCommit ? "contracts/market-catalog-feat164.candidate.json" : "contracts/market-catalog.candidate.json";
  const receiptPath = path.join(desktopRoot, receipt);
  const hash = digest(bytes);
  let base;
  if (immutableCommit) {
    const committed = verifyBase(connectorsRoot, immutableCommit);
    assert.equal(git(connectorsRoot, "rev-parse", "HEAD").toString().trim(), immutableCommit,
      "FEAT-164 catalog requires its qualified checkout");
    assert.ok(bytes.equals(committed), "Catalog source differs from its qualified Git object");
    base = immutableCommit;
  } else {
    const previous = existsSync(receiptPath) ? JSON.parse(readFileSync(receiptPath, "utf8")) : null;
    if (check) assert.ok(previous, "Catalog receipt missing; run the explicit sync entry first");
    if (previous) {
      assert.equal(previous.schema_version, 1);
      assert.equal(previous.mode, "local_worktree_candidate");
      assert.equal(previous.release, false);
      assert.equal(previous.authority, `yijie-connectors/${source}`);
      assert.equal(previous.generated, output);
      verifyBase(connectorsRoot, previous.base_commit);
    }
    // Replay the recorded generation baseline. A no-op sync must also remain
    // reproducible after unrelated commits. Only an explicit sync of changed
    // catalog bytes records a new baseline, still as a local worktree candidate.
    base = previous && (check || previous.source_sha256 === hash)
      ? previous.base_commit : git(connectorsRoot, "rev-parse", "HEAD").toString().trim();
    if (!previous || base !== previous.base_commit) verifyBase(connectorsRoot, base);
  }
  const manifest = Buffer.from(JSON.stringify({
    schema_version: 1, mode: immutableCommit ? "immutable_local_candidate" : "local_worktree_candidate", release: false,
    ...(immutableCommit ? { feature: "FEAT-164", source_commit: immutableCommit } : {}),
    authority: `yijie-connectors/${source}`, base_commit: base,
    source_sha256: hash, generated: output,
  }, null, 2) + "\n");
  const outputs = [[output, bytes], [receipt, manifest]];
  if (check) {
    for (const [name, expected] of outputs) {
      assert.ok(readFileSync(path.join(desktopRoot, name)).equals(expected),
        `${name}: catalog source/generated bytes or recorded provenance differ`);
    }
  } else {
    for (const [name, expected] of outputs) {
      const file = path.join(desktopRoot, name);
      if (!existsSync(file) || !readFileSync(file).equals(expected)) writeFileSync(file, expected);
    }
  }
  return { count: catalog.catalog.length, baseCommit: base, sourceSha256: hash };
}
